/** 意图→技能路由（首个命中的关键词为准；无命中返回 null） */
export function detectSkill(question: string): SkillHint | null {
  for (const s of SKILLS) {
    if (s.keywords.some((k) => k.length >= 2 && question.includes(k))) {
      return { name: s.name, hint: s.hint, keywords: s.keywords };
    }
  }
  return null;
}
