/** 简单分词：把问事与课象切成候选词（中文按常见语义词匹配） */
function queryTokens(question: string, raw: unknown): string[] {
  const r = raw as {
    kename?: string;
    本卦?: string;
    sanchuan?: string[];
    爻?: Array<{ 六亲?: string }>;
  } | null;
  const tokens = new Set<string>();
  const push = (s: string) => s && tokens.add(s);
  push(r?.kename ?? "");
  push(r?.本卦?.split("（")[0] ?? "");
  (r?.sanchuan ?? []).forEach(push);
  (r?.爻 ?? []).forEach((y) => y?.六亲 && push(y.六亲));
  // 常见事类词
  for (const w of [
    "事业",
    "工作",
    "升职",
    "求职",
    "感情",
    "婚姻",
    "恋",
    "财",
    "求财",
    "健康",
    "病",
    "出行",
    "旅行",
    "寻人",
    "运",
    "学业",
    "考试",
    "口舌",
  ]) {
    if (question.includes(w)) push(w);
  }
  return [...tokens].filter((t) => t.length >= 2);
}

/** 检索最相关断例（最多 n 条） */
export function searchDuanli(algorithmId: string, raw: unknown, question: string, n = 3): Duanli[] {
  const tokens = queryTokens(question, raw);
  const scored = DUANLI.map((d) => {
    let score = 0;
    for (const k of d.keywords) {
      if (tokens.some((t) => t === k || t.includes(k) || k.includes(t))) score += 1;
    }
    if (d.类型 === "六壬" && algorithmId === "daliuren") score += 1;
    if (d.类型 === "梅花" && algorithmId === "meihua") score += 1;
    if (d.类型 === "六爻" && algorithmId === "liuyao") score += 1;
    return { d, score };
  })
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, n).map((x) => x.d);
}

/** 注入上下文：参考断例区块 */
export function duanliContext(algorithmId: string, raw: unknown, question: string): string {
  const found = searchDuanli(algorithmId, raw, question, 3);
  if (!found.length) return "";
  return (
    "\n\n【参考断例，可据此引经据典，注明出处】\n" +
    found.map((d, i) => `${i + 1}. 《${d.书}》【${d.卦}】：${d.原文}（断义：${d.断义}）`).join("\n")
  );
}
